import logging
from typing import Optional

from fastapi import APIRouter, Depends, HTTPException, Response, status
from fastapi.responses import PlainTextResponse
from sqlalchemy.orm import Session

from app.analysis.graph_service import build_project_dependency_graph
from app.analysis.models import ProjectAnalysis
from app.analysis.service import analysis_languages_are_current, run_analysis_for_project
from app.api.auth import get_current_user_optional
from app.api.helpers import download_name, get_authorized_project
from app.database import get_db
from app.migration.service import build_migration_plan, migration_plan_markdown
from app.models.db import ProjectAnalysisRecord, ProjectFile, User

logger = logging.getLogger(__name__)

router = APIRouter(tags=["downloads"])


@router.get("/projects/{project_id}/migration-plan/download", response_class=PlainTextResponse)
def download_migration_plan(
    project_id: str,
    db: Session = Depends(get_db),
    current_user: Optional[User] = Depends(get_current_user_optional),
) -> PlainTextResponse:
    """Download the migration plan as a portable Markdown report."""
    project = get_authorized_project(project_id, db, current_user)
    try:
        plan = build_migration_plan(db, project_id)
    except RuntimeError as exc:
        raise HTTPException(status_code=status.HTTP_409_CONFLICT, detail=str(exc))
    content = migration_plan_markdown(plan, project.display_name)
    return PlainTextResponse(
        content,
        media_type="text/markdown; charset=utf-8",
        headers={"Content-Disposition": f'attachment; filename="{download_name(project.display_name)}-migration-plan.md"'},
    )


